-- symphony-store schema for PostgreSQL, v1: the SQLite schema up to migration 0005 in one step.
-- Integers are BIGINT; timestamps are unix epoch milliseconds (UTC); JSON is stored as text.

CREATE TABLE IF NOT EXISTS runs (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    issue_id         TEXT   NOT NULL,
    issue_identifier TEXT   NOT NULL,
    issue_title      TEXT,
    attempt          BIGINT NOT NULL DEFAULT 0,
    worker_host      TEXT,
    workspace_path   TEXT,
    status           TEXT   NOT NULL DEFAULT 'running'
                     CHECK (status IN ('running', 'succeeded', 'failed', 'cancelled', 'blocked')),
    error            TEXT,
    turns            BIGINT NOT NULL DEFAULT 0,
    started_at       BIGINT NOT NULL,
    finished_at      BIGINT,
    duration_ms      BIGINT,
    input_tokens     BIGINT NOT NULL DEFAULT 0,
    output_tokens    BIGINT NOT NULL DEFAULT 0,
    total_tokens     BIGINT NOT NULL DEFAULT 0,
    last_event_seq   BIGINT NOT NULL DEFAULT 0
);

CREATE INDEX IF NOT EXISTS runs_issue_identifier_idx ON runs (issue_identifier, id);
CREATE INDEX IF NOT EXISTS runs_status_idx ON runs (status, id);
CREATE INDEX IF NOT EXISTS runs_started_at_idx ON runs (started_at);
CREATE INDEX IF NOT EXISTS runs_issue_id_idx ON runs (issue_id, id);

CREATE TABLE IF NOT EXISTS run_events (
    run_id  BIGINT NOT NULL REFERENCES runs (id) ON DELETE CASCADE,
    seq     BIGINT NOT NULL,
    at      BIGINT NOT NULL,
    kind    TEXT   NOT NULL,
    message TEXT,
    payload TEXT,
    PRIMARY KEY (run_id, seq)
);

CREATE INDEX IF NOT EXISTS run_events_at_idx ON run_events (at);

CREATE TABLE IF NOT EXISTS retry_queue (
    issue_id       TEXT PRIMARY KEY,
    attempt        BIGINT NOT NULL,
    due_at         BIGINT NOT NULL,
    identifier     TEXT   NOT NULL,
    issue_url      TEXT,
    error          TEXT,
    worker_host    TEXT,
    workspace_path TEXT
);

CREATE TABLE IF NOT EXISTS run_costs (
    run_id         BIGINT PRIMARY KEY REFERENCES runs (id) ON DELETE CASCADE,
    cost_micro_usd BIGINT NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS control (
    key   TEXT PRIMARY KEY,
    value TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS tasks (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title       TEXT,
    prompt      TEXT   NOT NULL,
    repo        TEXT,
    branch      TEXT,
    backend     TEXT,
    max_tokens  BIGINT,
    timeout_ms  BIGINT,
    metadata    TEXT,
    status      TEXT   NOT NULL DEFAULT 'queued'
                CHECK (status IN ('queued', 'running', 'succeeded', 'failed', 'cancelled', 'blocked')),
    result      TEXT,
    error       TEXT,
    attempts    BIGINT NOT NULL DEFAULT 0,
    created_at  BIGINT NOT NULL,
    updated_at  BIGINT NOT NULL,
    started_at  BIGINT,
    finished_at BIGINT
);

CREATE INDEX IF NOT EXISTS tasks_status_idx ON tasks (status, id);

CREATE TABLE IF NOT EXISTS leases (
    key        TEXT   PRIMARY KEY,
    owner      TEXT   NOT NULL,
    expires_at BIGINT NOT NULL
);

CREATE INDEX IF NOT EXISTS leases_owner_idx ON leases (owner);
